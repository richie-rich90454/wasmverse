import type { BuildContextRecord } from "@sharedKernel/BuildContextRecord.ts";
import type { RuntimeAssetAssemblerContract } from "@serverAtelier/runtimeAssemblers/RuntimeAssetAssemblerContract.ts";
import { EMBEDDED_ASSET_RESOLVER_GLUE_SOURCE } from "@serverAtelier/runtimeAssemblers/EmbeddedAssetResolverGlue.ts";
import { FileSystemOperations } from "@serverAtelier/utilities/FileSystemOperations.ts";
const ELM_LOADER_FILE_NAME = "elm-loader.js";
const ELM_LOADER_SOURCE = [
    EMBEDDED_ASSET_RESOLVER_GLUE_SOURCE,
    "export async function loadElmModule(baseUrl, attemptIdentifier) {",
    "    delete globalThis.Elm;",
    "    await import(resolve(`${baseUrl}/app.js?attempt=${encodeURIComponent(attemptIdentifier)}`));",
    "    const elmExports = globalThis.Elm;",
    "    delete globalThis.Elm;",
    "    if (!elmExports) {",
    "        throw new Error('The compiled Elm module registered no Elm program.');",
    "    }",
    "    const elmProgramList = Object.values(elmExports).filter(",
    "        (candidate) => candidate && typeof candidate.init === 'function',",
    "    );",
    "    const elmProgram = elmProgramList[elmProgramList.length - 1];",
    "    if (!elmProgram) {",
    "        throw new Error('The compiled Elm module registered no Elm program.');",
    "    }",
    "    await new Promise((resolve, reject) => {",
    "        let isSettled = false;",
    "        const portHandlers = [];",
    "        const finish = (failure) => {",
    "            if (isSettled) {",
    "                return;",
    "            }",
    "            isSettled = true;",
    "            for (const portAndHandler of portHandlers) {",
    "                portAndHandler[0].unsubscribe(portAndHandler[1]);",
    "            }",
    "            if (failure) {",
    "                reject(failure);",
    "            } else {",
    "                resolve();",
    "            }",
    "        };",
    "        const app = elmProgram.init({",
    "            flags: { programArguments: [...(globalThis.wasmverseProgramArguments ?? [])] },",
    "        });",
    "        const appPorts = app.ports;",
    "        const requirePort = (portName) => {",
    "            if (!appPorts || !appPorts[portName]) {",
    "                throw new Error(`The Elm entry module must declare a ${portName} port (port module protocol).`);",
    "            }",
    "            return appPorts[portName];",
    "        };",
    "        const stdoutPort = requirePort('wasmverseStdout');",
    "        const donePort = requirePort('wasmverseDone');",
    "        const stdinRequestPort = appPorts && appPorts.wasmverseStdinRequest;",
    "        const stdinPort = appPorts && appPorts.wasmverseStdin;",
    "        const fileRequestPort = appPorts && appPorts.wasmverseFileRequest;",
    "        const fileResponsePort = appPorts && appPorts.wasmverseFileResponse;",
    "        const stdoutHandler = (lineText) => {",
    "            globalThis.wasmversePrint(String(lineText));",
    "        };",
    "        stdoutPort.subscribe(stdoutHandler);",
    "        portHandlers.push([stdoutPort, stdoutHandler]);",
    "        const doneHandler = () => {",
    "            setTimeout(() => finish(), 0);",
    "        };",
    "        donePort.subscribe(doneHandler);",
    "        portHandlers.push([donePort, doneHandler]);",
    "        if (stdinRequestPort && stdinPort) {",
    "            const stdinHandler = () => {",
    "                let lineText;",
    "                try {",
    "                    lineText = globalThis.wasmverseReadLine();",
    "                } catch (inputError) {",
    "                    finish(inputError);",
    "                    return;",
    "                }",
    "                queueMicrotask(() => {",
    "                    if (!isSettled) {",
    "                        stdinPort.send(String(lineText));",
    "                    }",
    "                });",
    "            };",
    "            stdinRequestPort.subscribe(stdinHandler);",
    "            portHandlers.push([stdinRequestPort, stdinHandler]);",
    "        }",
    "        if (fileRequestPort && fileResponsePort) {",
    "            const fileHandler = (requestedPath) => {",
    "                let fileContents = '';",
    "                try {",
    "                    fileContents = globalThis.wasmverseReadFile(String(requestedPath));",
    "                } catch (fileError) {",
    "                    fileContents = '';",
    "                }",
    "                queueMicrotask(() => {",
    "                    if (!isSettled) {",
    "                        fileResponsePort.send([String(requestedPath), fileContents]);",
    "                    }",
    "                });",
    "            };",
    "            fileRequestPort.subscribe(fileHandler);",
    "            portHandlers.push([fileRequestPort, fileHandler]);",
    "        }",
    "    });",
    "}",
    "",
].join("\n");
class ElmLoaderRuntimeAssembler implements RuntimeAssetAssemblerContract {
    private readonly fileSystemOperations: FileSystemOperations;
    constructor(fileSystemOperations: FileSystemOperations) {
        this.fileSystemOperations = fileSystemOperations;
    }
    async assembleRuntimeInto(context: BuildContextRecord): Promise<void> {
        await this.fileSystemOperations.ensureDirectoryExists(context.runtimeDirectory);
        await this.fileSystemOperations.writeTextFile(
            `${context.runtimeDirectory}/${ELM_LOADER_FILE_NAME}`,
            ELM_LOADER_SOURCE,
        );
    }
}
export { ElmLoaderRuntimeAssembler };
